// Writes web/lib/tracks.js (lesson ids per track) so the server can check certificates against the real course.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = await build({ entryPoints: [`${root}src/content/course.js`], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'error' });
const { TRACKS, lessonsInTrack } = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);
const tracks = Object.fromEntries(TRACKS.map((t) => [t.id, { title: t.title, short: t.short, lessons: lessonsInTrack(t.id) }]));
writeFileSync(`${root}web/lib/tracks.js`, '// Generated by scripts/gen-tracks.mjs from the course. Do not edit.\nexport default ' + JSON.stringify(tracks, null, 2) + ';\n');
console.log('tracks.js:', Object.entries(tracks).map(([id, t]) => `track ${id} = ${t.lessons.length} lessons`).join(', '));
